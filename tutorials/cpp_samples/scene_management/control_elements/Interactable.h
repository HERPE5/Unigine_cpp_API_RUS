// Базовый интерфейс для интерактивных элементов управления (кнопки, рычаги, вентили).
// Предоставляет общие методы взаимодействия и получения значения.
// Производные классы реализуют конкретное поведение элемента управления.

#pragma once
#include <UnigineGame.h>

// Абстрактный интерфейс для объектов сцены, с которыми может взаимодействовать игрок.
class Interactable
{
public:
	// Приоритет обновления гарантирует, что интерактивные элементы обновляются раньше реакторов
	static const int interactable_update_priority;

	// Вызывается каждый кадр, пока игрок удерживает клавишу взаимодействия
	virtual void use(Unigine::PlayerPtr player, Unigine::Math::vec3 intersection_point) = 0;
	// Возвращает нормализованное значение состояния (0-1) для чтения реакторами
	virtual float getValue() = 0;
};